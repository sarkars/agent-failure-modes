#!/usr/bin/env python3
"""Rebuild the roadmap's generated summaries from the catalog tables.

Run from anywhere:  python3 -I agents/by-capability/human-machine-interface/roadmap/tools/rebuild_summary.py

Reads every catalog table (rows whose first cell looks like AB-01 and that have 9 cells), then rewrites:
  - roadmap/index.md                                  (one line per row)
  - the blocks between <!-- BEGIN:x --> and <!-- END:x --> in roadmap/README.md
  - the roadmap count line in the area README         (block 'roadmap-count')
Library status comes from the last cell: Written / Covered / Extends / otherwise New.
"""
import re, glob, os, collections

ROADMAP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AREA = os.path.dirname(ROADMAP)
SKIP = {"README.md", "index.md", "execution-plan.md"}
DESC = {
    "chat-and-core.md": "Remaining chat and core families, plus channel selection",
    "embedded-copilots.md": "Embedded copilots: upselling, context, first response, obvious questions",
    "response-time.md": "Speed, waiting, and pacing, all channels",
    "response-structure-and-length.md": "Reply structure, length, chunking, and closers such as 'ok' and 'bye'",
    "language-and-locale.md": "Language, reading level, and locale",
    "conversation-frameworks.md": "Sales, support, style matching, and other frameworks",
    "voice.md": "Voice agents: timing, speaking, safety, and bridging channels",
    "voice-listening-and-transcription.md": "Voice listening and transcription",
    "privacy-governance-and-access.md": "Privacy, governance, ethics, access control, and external services",
    "effort-completeness-and-memory.md": "Effort, completeness, and memory",
    "emerging-surfaces.md": "Emerging surfaces: agentic commerce, browser agents, tool ecosystems, meetings, companions, hiring, pricing incentives",
    "visual-and-oversight.md": "Visual design and human-oversight UI for agents",
    "agent-types.md": "Failures by agent type (coding, data, IT, finance, healthcare, and more) and cross-agent additions",
    "conversation-design.md": "Dialogue mechanics, refusals and boundaries, and error recovery",
    "interface-and-persona.md": "Persona and tone, onboarding, chat interface, accessibility, and multimodal input",
    "handoff-measurement-and-operations.md": "Human handoff, measurement, model changes, proactive agents, and group chats",
    "service-and-vertical-patterns.md": "Drive-thru, in-car, government, travel, banking, insurance, health scheduling, real estate, and outbound rules",
}
ORDER = list(DESC)

def status_of(cell):
    for s in ("Written", "Covered", "Extends"):
        if cell.startswith(f"**{s}**"):
            return s
    return "New"

def load():
    rows = []
    for path in sorted(glob.glob(os.path.join(ROADMAP, "*.md"))):
        name = os.path.basename(path)
        if name in SKIP:
            continue
        for line in open(path).read().split("\n"):
            if re.match(r"^\| [A-Z]{2}-[A-Z]?\d+ \|", line):
                c = [x.strip() for x in line.strip().strip("|").split("|")]
                if len(c) >= 9:
                    rows.append(dict(id=c[0], name=c[1], file=name, cause=c[6], fix=c[7], status=status_of(c[8])))
    return rows

def block(text, name, body):
    pat = re.compile(rf"(<!-- BEGIN:{name} -->\n).*?(<!-- END:{name} -->)", re.S)
    assert pat.search(text), f"missing markers for {name}"
    return pat.sub(lambda m: m.group(1) + body.rstrip("\n") + "\n" + m.group(2), text)

def main():
    rows = load()
    n = len(rows)
    st = collections.Counter(r["status"] for r in rows)
    cause = collections.Counter(r["cause"] for r in rows)
    fix = collections.Counter(r["fix"] for r in rows)
    per = collections.defaultdict(collections.Counter)
    for r in rows:
        per[r["file"]][r["status"]] += 1
    files = [f for f in ORDER if f in per] + sorted(f for f in per if f not in ORDER)

    # index.md
    idx = ["# HMI Roadmap Index: All Catalogued Patterns", "",
           f"> One line per catalogued failure ({n} rows). Details, goals, and metrics are in each file. Labels are explained in the [roadmap README](README.md). This file is generated by `tools/rebuild_summary.py`.", "",
           "| ID | Pattern | File | In the library | Root cause | Better model alone? |", "|---|---|---|---|---|---|"]
    for f in files:
        for r in [x for x in rows if x["file"] == f]:
            idx.append(f"| {r['id']} | {r['name']} | [{f}]({f}) | {r['status']} | {r['cause']} | {r['fix']} |")
    open(os.path.join(ROADMAP, "index.md"), "w").write("\n".join(idx) + "\n")

    # README blocks
    table = ["| File | Area | Rows | Written | New | Extends | Covered |", "|---|---|---|---|---|---|---|"]
    for f in files:
        c = per[f]
        table.append(f"| [{f}]({f}) | {DESC.get(f, f)} | {sum(c.values())} | {c['Written']} | {c['New']} | {c['Extends']} | {c['Covered']} |")
    table.append(f"| | **Total** | **{n}** | **{st['Written']}** | **{st['New']}** | **{st['Extends']}** | **{st['Covered']}** |")
    result = (f"**Result: {n} rows, of which {st['Written']} are Written, {st['New']} are New, "
              f"{st['Extends']} Extend an existing pattern, and {st['Covered']} are already Covered.**")
    to_write = st["New"] + st["Extends"]
    def pct(x): return f"{x / n:.0%}"
    rc = ["## Root cause and the model question",
          "Every row carries two extra labels: its **primary root cause**, and whether **a better model alone would fix it**. They are my judgments, one label per row, not measurements. The catalog leans toward human-interface, design, and policy failures, so a catalog of raw model failures would show a higher model share.", "",
          "| Primary root cause | Rows | Share |", "|---|---|---|",
          f"| Model: a stronger model plausibly reduces it | {cause['Model']} | {pct(cause['Model'])} |",
          f"| Reliability: state, verification, enforcement, evals, latency | {cause['Reliability']} | {pct(cause['Reliability'])} |",
          f"| Business context: your data, entitlements, rules, workflows, UX | {cause['Business context']} | {pct(cause['Business context'])} |",
          f"| Governance: incentives, law, and decisions | {cause['Governance']} | {pct(cause['Governance'])} |", "",
          "| Better model alone? | Rows | Share |", "|---|---|---|",
          f"| Yes, largely | {fix['Yes']} | {pct(fix['Yes'])} |",
          f"| Partly: helps, residual remains | {fix['Partly']} | {pct(fix['Partly'])} |",
          f"| No: persists with a perfect model | {fix['No']} | {pct(fix['No'])} |", "",
          f"If every \"Partly\" were solved, models would fix up to {pct(fix['Yes'] + fix['Partly'])}. If none were, {pct(fix['Yes'])}. A one-page list of all rows is in the [index](index.md)."]
    p = os.path.join(ROADMAP, "README.md")
    t = open(p).read()
    t = block(t, "catalog-table", "\n".join(table))
    t = block(t, "result", result)
    t = block(t, "root-cause", "\n".join(rc))
    open(p, "w").write(t)

    # area README count line
    ap = os.path.join(AREA, "README.md")
    a = open(ap).read()
    if "<!-- BEGIN:roadmap-count -->" in a:
        line = (f"[{n} catalogued patterns](roadmap/README.md) with goals and metrics, checked against the existing library "
                f"({st['Written']} written, {st['New']} new, {st['Extends']} that extend an existing pattern, {st['Covered']} already covered). "
                f"The [execution plan](roadmap/execution-plan.md) orders the {to_write + st['Written']} to write.")
        a = block(a, "roadmap-count", line)
        open(ap, "w").write(a)
    print(f"rows={n} written={st['Written']} new={st['New']} extends={st['Extends']} covered={st['Covered']}")

if __name__ == "__main__":
    main()
